import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const entries = await Promise.all(["local", "staging", "production"].map(async (environment) => [environment, JSON.parse(await readFile(resolve(root, "deployments", `${environment}.json`), "utf8"))]));
const content = `// Generated by scripts/generate-deployment-config.mjs. Do not edit.\nexport const deploymentManifests = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const;\nexport type DeploymentEnvironment = keyof typeof deploymentManifests;\n`;
await writeFile(resolve(root, "packages/web/src/generated/deployment-manifests.ts"), content);
