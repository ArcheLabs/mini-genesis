import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const allEnvironments = ["local", "staging", "production"];
const buildEnvironment = process.env.VITE_DEPLOYMENT_ENV;
const includeAll = process.argv.includes("--all") || !buildEnvironment || buildEnvironment === "local";
const environments = includeAll
  ? allEnvironments
  : buildEnvironment === "staging"
    ? ["staging", "production"]
    : buildEnvironment === "production"
      ? ["production"]
      : null;
if (!environments) throw new Error(`Unsupported VITE_DEPLOYMENT_ENV: ${buildEnvironment}`);
const entries = await Promise.all(environments.map(async (environment) => [environment, JSON.parse(await readFile(resolve(root, "deployments", `${environment}.json`), "utf8"))]));
const content = `// Generated by scripts/generate-deployment-config.mjs. Do not edit.\nexport const availableDeploymentEnvironments = ${JSON.stringify(environments)} as const;\nexport const deploymentManifests = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const;\nexport type DeploymentEnvironment = "local" | "staging" | "production";\n`;
await writeFile(resolve(root, "packages/web/src/generated/deployment-manifests.ts"), content);
